#!/usr/bin/env bash
# Generates cypress/e2e-patched/spec.cy.js from the official spec with ONLY the two harness bugs fixed
# (they fail identically for TodoMVC's own localStorage reference apps under Cypress 15):
#   1. `.invoke('reset')` on a sinon spy -> `.invoke('resetHistory')` (spy.reset no longer exists)
#   2. persistence test reuses element aliases across cy.reload() -> re-alias the fresh <li>s after reload,
#      by their text (what the original aliases pointed at), since under All finished to-dos sink below open ones
set -euo pipefail
T="$(cd "$(dirname "$0")/.." && pwd)/vendor/todomvc/cypress"
mkdir -p "$T/e2e-patched"
python3 - "$T/e2e/spec.cy.js" "$T/e2e-patched/spec.cy.js" <<'PY'
import sys
src, dst = sys.argv[1:]
s = open(src).read()
a = s.count(".invoke('reset')"); s = s.replace(".invoke('reset')", ".invoke('resetHistory')")
old = "cy.reload().then(testState)"
b = s.count(old)
s = s.replace(old, "cy.reload().then(() => {\n          cy.contains(selectors.todoItems, TODO_ITEM_ONE).as('firstTodo')\n          cy.contains(selectors.todoItems, TODO_ITEM_TWO).as('secondTodo')\n        }).then(testState)")
assert a == 1 and b == 1, (a, b)
open(dst, "w").write("// GENERATED by tools/patch-spec.sh from cypress/e2e/spec.cy.js — only the two harness-bug fixes differ.\n" + s)
PY
diff "$T/e2e/spec.cy.js" "$T/e2e-patched/spec.cy.js" || true
